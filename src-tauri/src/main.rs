// Hide the console window on Windows release builds
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

use std::fs;
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use tauri::{ipc::InvokeBody, ipc::Request, Manager, State};

// Data layout (the export zip uses the same layout):
//   <data dir>/people.json   {"app":"whoisthis","version":2,"people":[...]}, `photo` is a file name
//   <data dir>/images/<photo>
const PEOPLE_FILE: &str = "people.json";
const IMAGES: &str = "images";
const DATA_DIR_NAME: &str = "whoisthis-data";

struct DataDir(PathBuf);

impl DataDir {
    fn images(&self) -> PathBuf {
        self.0.join(IMAGES)
    }
}

/// Next to the executable when that folder is writable (portable exe, per-user install),
/// otherwise the OS app data folder (MSI in Program Files, Linux packages, macOS .app bundles).
fn resolve_data_dir(app: &tauri::App) -> Result<PathBuf, Box<dyn std::error::Error>> {
    #[cfg(not(target_os = "macos"))]
    if let Some(dir) = std::env::current_exe()
        .ok()
        .and_then(|exe| exe.parent().map(|p| p.join(DATA_DIR_NAME)))
    {
        if is_writable(&dir) {
            return Ok(dir);
        }
    }
    Ok(app.path().app_data_dir()?)
}

#[cfg(not(target_os = "macos"))]
fn is_writable(dir: &Path) -> bool {
    let probe = dir.join(".write-test");
    let ok = fs::create_dir_all(dir).is_ok() && fs::write(&probe, b"").is_ok();
    let _ = fs::remove_file(&probe);
    ok
}

/// Photo file names are generated by the app; reject anything else (e.g. "../x" from a crafted zip).
fn check_name(name: &str) -> Result<&str, String> {
    let ok = !name.is_empty()
        && name.len() <= 128
        && !name.starts_with('.')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_'));
    if ok { Ok(name) } else { Err(format!("invalid image name: {name}")) }
}

/// Write to a temp file and rename, so a crash never leaves a half-written file.
fn write_atomic(path: &Path, contents: &[u8]) -> std::io::Result<()> {
    let tmp = path.with_extension("tmp");
    fs::write(&tmp, contents)?;
    fs::rename(&tmp, path)
}

fn err(e: impl std::fmt::Display) -> String {
    e.to_string()
}

/// Photos are shown with convertFileSrc(`${images_dir}/${photo}`).
#[tauri::command]
fn images_dir(dir: State<DataDir>) -> String {
    dir.images().to_string_lossy().into_owned()
}

/// Returns people.json, or None on first run.
#[tauri::command]
fn load_people(dir: State<DataDir>) -> Result<Option<String>, String> {
    match fs::read_to_string(dir.0.join(PEOPLE_FILE)) {
        Ok(s) => Ok(Some(s)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(err(e)),
    }
}

#[tauri::command]
fn save_people(dir: State<DataDir>, json: String) -> Result<(), String> {
    write_atomic(&dir.0.join(PEOPLE_FILE), json.as_bytes()).map_err(err)
}

/// Raw request body = image bytes, header `name` = file name.
#[tauri::command]
fn save_image(dir: State<DataDir>, request: Request<'_>) -> Result<(), String> {
    let InvokeBody::Raw(bytes) = request.body() else {
        return Err("expected raw image bytes".into());
    };
    let name = request.headers().get("name").and_then(|v| v.to_str().ok()).unwrap_or("");
    write_atomic(&dir.images().join(check_name(name)?), bytes).map_err(err)
}

#[tauri::command]
fn delete_image(dir: State<DataDir>, name: String) -> Result<(), String> {
    match fs::remove_file(dir.images().join(check_name(&name)?)) {
        Err(e) if e.kind() != std::io::ErrorKind::NotFound => Err(err(e)),
        _ => Ok(()),
    }
}

#[tauri::command]
fn open_data_dir(dir: State<DataDir>) -> Result<(), String> {
    #[cfg(target_os = "windows")]
    let program = "explorer";
    #[cfg(target_os = "macos")]
    let program = "open";
    #[cfg(not(any(target_os = "windows", target_os = "macos")))]
    let program = "xdg-open";
    std::process::Command::new(program).arg(&dir.0).spawn().map(|_| ()).map_err(err)
}

/// Photo file names referenced by a people.json document.
fn photo_names(json: &str) -> Result<Vec<String>, String> {
    let doc: serde_json::Value = serde_json::from_str(json).map_err(err)?;
    if doc["app"] != "whoisthis" || !doc["people"].is_array() {
        return Err("not a WhoIsThis file".into());
    }
    Ok(doc["people"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|p| p["photo"].as_str())
        .filter(|s| check_name(s).is_ok())
        .map(String::from)
        .collect())
}

/// Writes people.json plus the images it references. JPEGs are stored uncompressed (they don't shrink).
/// `time` is the local [year, month, day, hour, minute, second] from the webview: zip timestamps are
/// local time, which std cannot provide.
#[tauri::command]
fn export_zip(dir: State<DataDir>, path: String, json: String, time: [u16; 6]) -> Result<(), String> {
    use zip::write::SimpleFileOptions;
    use zip::CompressionMethod::{Deflated, Stored};

    let [y, mo, d, h, mi, s] = time;
    let mtime = zip::DateTime::from_date_and_time(y, mo as u8, d as u8, h as u8, mi as u8, s as u8)
        .unwrap_or_default();
    let options = SimpleFileOptions::default().last_modified_time(mtime);
    let mut zip = zip::ZipWriter::new(fs::File::create(&path).map_err(err)?);
    zip.start_file(PEOPLE_FILE, options.compression_method(Deflated)).map_err(err)?;
    zip.write_all(json.as_bytes()).map_err(err)?;
    for name in photo_names(&json)? {
        let bytes = fs::read(dir.images().join(&name)).map_err(|e| format!("{name}: {e}"))?;
        zip.start_file(format!("{IMAGES}/{name}"), options.compression_method(Stored))
            .map_err(err)?;
        zip.write_all(&bytes).map_err(err)?;
    }
    zip.finish().map_err(err)?;
    Ok(())
}

/// Copies the zip's images into the data folder and returns its people.json for the app to merge.
/// A .json file (the old export format with embedded photos) is returned as is.
#[tauri::command]
fn import_file(dir: State<DataDir>, path: String) -> Result<String, String> {
    if path.to_lowercase().ends_with(".json") {
        return fs::read_to_string(&path).map_err(err);
    }
    let mut zip = zip::ZipArchive::new(fs::File::open(&path).map_err(err)?).map_err(err)?;
    let mut json = String::new();
    zip.by_name(PEOPLE_FILE)
        .map_err(|_| "people.json not found in zip".to_string())?
        .read_to_string(&mut json)
        .map_err(err)?;
    for name in photo_names(&json)? {
        let mut bytes = Vec::new();
        zip.by_name(&format!("{IMAGES}/{name}"))
            .map_err(|_| format!("{name} not found in zip"))?
            .read_to_end(&mut bytes)
            .map_err(err)?;
        write_atomic(&dir.images().join(&name), &bytes).map_err(err)?;
    }
    Ok(json)
}

fn main() {
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .setup(|app| {
            let dir = resolve_data_dir(app)?;
            let images = dir.join(IMAGES);
            fs::create_dir_all(&images)?;
            // Let the webview load photos through the asset protocol (convertFileSrc)
            app.asset_protocol_scope().allow_directory(&images, false)?;
            app.manage(DataDir(dir));
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            images_dir,
            load_people,
            save_people,
            save_image,
            delete_image,
            open_data_dir,
            export_zip,
            import_file
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
